"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const main = read("app/src/main/java/com/fz/office/MainActivity.java");
const pdf = read("app/src/main/java/com/fz/office/pdf/PdfViewerActivity.java");
assert(main.includes('"application/pdf"'), "PDF must be in the document picker");
assert(main.includes('lower.endsWith(".pdf")'), "PDF filename route is missing");
assert(main.includes("new Intent(this, PdfViewerActivity.class)"), "PDF must open in the built-in reader");
assert(pdf.includes("new PdfRenderer(opened)"), "PDF reader must use Android PdfRenderer");
assert(pdf.includes("RENDER_MODE_FOR_DISPLAY"), "PDF page render mode is missing");
assert(pdf.includes("changePage(-1)") && pdf.includes("changePage(1)"), "Previous/next controls are required");
assert(pdf.includes("changeZoom(-0.15f)") && pdf.includes("changeZoom(0.15f)"), "PDF zoom controls are required");
assert(pdf.includes("MAX_BITMAP_PIXELS"), "PDF bitmap memory use must be bounded");
assert(pdf.includes("Original file unchanged"), "PDF reader must preserve the source file");
assert(pdf.includes("applySafeAreaInsets(root)"), "PDF reader must respect system bars");
assert(pdf.includes("copyToPrivateCache"), "PDF content providers must be handled using a private cache copy");
assert(!pdf.includes("openOutputStream(documentUri)"), "PDF reader must not write to the original file");
console.log("Offline PDF reader checks passed.");
